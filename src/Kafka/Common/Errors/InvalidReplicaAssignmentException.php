declare(strict_types=1);

namespace Protocol\Kafka\Common\Errors;

use Exception;

/**
 * Replica assignment is invalid.
 *
 * Error code 39, Kafka 0.10.1 (CreateTopics, KIP-4).
 */
class InvalidReplicaAssignmentException extends KafkaException implements ServerExceptionInterface
{
    public function __construct(array $context = [], ?Exception $previous = null)
    {
        parent::__construct($context, self::INVALID_REPLICA_ASSIGNMENT, $previous);
    }
}
